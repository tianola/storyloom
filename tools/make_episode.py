"""One command from a written script to a quality-checked master.

    python tools/make_episode.py --episode work/X --dry-run     # what each stage would do
    python tools/make_episode.py --episode work/X                # run every stage that is not done
    python tools/make_episode.py --episode work/X --from render  # start at a stage
    python tools/make_episode.py --episode work/X --only qc      # just these (comma separated)
    python tools/make_episode.py --episode work/X --ask-cmd "<cmd>"   # planner: prompt on stdin, JSON out
    python tools/make_episode.py --episode work/X --ask-api           # planner: Claude through the Anthropic API

Stages, in order (each is an existing tool; this file only sequences them):
  script     tools/qc_script.py          the script gate; nothing is synthesised for a script that fails
  narration  python/narrate.py           one wav per line + vo/manifest.json (Kokoro, offline)
  shots      tools/plan_shots.py         shots.json: which line plays over which beat or archive shot (kept if present)
  captions   tools/captions.py           word timings, captions.srt/.vtt, word_timing.json
  lengths    assemble_episode.py --shot-lengths-only    narration seconds per beat
  plan       tools/plan_storyboard.py    storyboard.json; without --ask-cmd it writes the brief and stops
  ingest     rollout_render.py ingest    archive clips (a missing source is an error, never a placeholder)
  render     rollout_render.py render    the 3D beats in Blender
  assemble   tools/assemble_episode.py   cut, grade, level, mux (captions as a soft stream)
  qc         tools/qc_episode.py         the master against the style contract

Resumable: `<episode>/qc/make-episode.json` records a digest of each finished stage's inputs. A stage
whose inputs have not changed and whose outputs exist is skipped; change the script and everything
downstream of it runs again. The run stops at the first failing stage with its exit code.
`shots.json` is generated by `plan_shots.py` unless the author already wrote one (never overwritten).
"""
import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

PY = sys.executable
STAGES = ["script", "narration", "shots", "captions", "lengths", "plan", "ingest", "render", "assemble", "qc"]


def _files(episode, *names):
    return [episode / n for n in names]


def _optional(episode, *names):
    """Inputs that only some episodes have (characters' voices): counted once they exist, so an
    episode without them keeps the digest it was built with."""
    return [episode / n for n in names if (episode / n).is_file()]


def has_characters(episode):
    """True when the episode casts characters who speak in their own voice (script/cast.json)."""
    return (episode / "script" / "cast.json").is_file()


def shot_table(episode):
    """The file that says what is on screen: cut.json for a cut-list episode, else shots.json."""
    return "cut.json" if (episode / "cut.json").is_file() else "shots.json"


def beat_renders(episode):
    """renders/3d/<beat>.mp4 for every 3D beat in the shot table: what the render stage owes the edit."""
    path = episode / shot_table(episode)
    if not path.is_file():
        return []
    body = json.loads(path.read_text(encoding="utf-8"))
    records = [s["source"] for s in body.get("shots", [])] if path.name == "cut.json" else body.values()
    beats = {s["name"] for s in records if s.get("kind") == "3d"}
    return [f"renders/3d/{b}.mp4" for b in sorted(beats)]


def inputs_of(stage, episode):
    """Files whose content decides whether a finished stage is still valid."""
    style = ROOT / "workflow" / "style.json"
    shots = shot_table(episode)
    table = {
        "script": _files(episode, "script/narration.md", "script/chapters.json", "script/claims.json",
                         "research/sources.md") + [style] + _optional(episode, "script/cast.json", "script/dramatisation.json"),
        "narration": _files(episode, "script/narration.md") + _optional(episode, "script/cast.json", "script/pronounce.json"),
        "shots": _files(episode, "vo/manifest.json", "archive.json", "script/shots-hint.json"),
        "captions": _files(episode, "vo/manifest.json", shots),
        "lengths": _files(episode, "vo/manifest.json", shots),
        "plan": _files(episode, "shot_lengths.json", shots, "vo/manifest.json") + [ROOT / "workflow" / "scenes.json"],
        "ingest": _files(episode, "archive.json", shots),
        "render": _files(episode, "storyboard.json", "shot_lengths.json", "word_timing.json")
        + _optional(episode, "mouth_timing.json"),
        # a re-rendered beat changes the film, so the renders themselves are inputs of the edit
        "assemble": _files(episode, "vo/manifest.json", shots, "shot_lengths.json", "storyboard.json",
                           *beat_renders(episode)),
        "qc": [episode / f"{episode.name}.mp4"],
    }
    return table[stage]


# The tool code each stage runs. A change here does not re-run a finished stage by itself (a render
# is hours, and most code changes do not touch a given episode); the run says which finished stages
# were built with older code, so `--force --only <stage>` is a decision rather than a guess.
CODE = {
    "script": ["tools/qc_script.py"],
    "narration": ["python/narrate.py", "python/eleven.py"],
    "shots": ["tools/plan_shots.py"],
    "captions": ["tools/captions.py", "tools/word_marks.py", "tools/lip_sync.py"],
    "lengths": ["tools/assemble_episode.py", "tools/edit/*.py"],
    "plan": ["tools/plan_storyboard.py", "workflow/storyboard.py"],
    "ingest": ["tools/archive_ingest.py", "tools/rollout_render.py"],
    "render": ["tools/rollout_render.py", "tools/blender/**/*.py", "tools/pixel/**/*.py"],
    "assemble": ["tools/assemble_episode.py", "tools/edit/*.py", "tools/compose/*.py", "tools/graphics/*.py",
                 "tools/look_pass.py", "tools/audio_finish.py", "tools/music_bed.py", "tools/sound_design.py",
                 "tools/loudness.py", "tools/captions.py"],
    "qc": ["tools/qc_episode.py"],
}


def code_of(stage, root=ROOT):
    return sorted({p for pattern in CODE[stage] for p in root.glob(pattern) if p.is_file()})


def code_digest(stage, root=ROOT):
    """Content of the stage's code, by path relative to the repo (so two files called common.py differ)."""
    h = hashlib.sha1()
    for p in code_of(stage, root):
        h.update(p.relative_to(root).as_posix().encode())
        h.update(p.read_bytes().replace(b"\r\n", b"\n"))   # a checkout's line endings are not a change
    return h.hexdigest()


def code_note(stage, record, root=ROOT):
    """A sentence when a finished stage was built with different code, else None. Records from before
    the code was tracked carry no digest and say nothing."""
    if record and record.get("code") and record["code"] != code_digest(stage, root):
        return f"built with older {stage} code; --force --only {stage} to redo it with the current code"
    return None


def digest(paths):
    h = hashlib.sha1()
    for p in paths:
        h.update(str(p.name).encode())
        h.update(p.read_bytes() if p.is_file() and p.stat().st_size < 200_000_000 else
                 (str(p.stat().st_size) + str(p.stat().st_mtime_ns)).encode() if p.is_file() else b"-")
    return h.hexdigest()


def outputs_exist(stage, episode):
    out = {
        "script": ["qc/script-qc.json"],
        "narration": ["vo/manifest.json"],
        "shots": [shot_table(episode)],
        "captions": ["vo/captions.srt", "word_timing.json"] + (["mouth_timing.json"] if has_characters(episode) else []),
        "lengths": ["shot_lengths.json"],
        "plan": ["storyboard.json"],
        "ingest": [],
        # a beat deleted to be redrawn is a missing output, not a finished stage
        "render": beat_renders(episode),
        "assemble": [f"{episode.name}.mp4"],
        "qc": ["qc/qc-report.json"],
    }[stage]
    return all((episode / o).is_file() for o in out)


def narration_request(episode):
    """The Kokoro request for the script: one utterance per line (ids as the script gate numbers them)."""
    import qc_script
    existing = episode / "script" / "narration-request.json"
    base = json.loads(existing.read_text(encoding="utf-8")) if existing.exists() else {}
    lines = qc_script.read_lines(episode)
    cast = qc_script.read_cast(episode)
    say_path = episode / "script" / "pronounce.json"
    say = json.loads(say_path.read_text(encoding="utf-8")) if say_path.exists() else {}
    narrator = (cast.get(qc_script.NARRATOR) or {}).get("voice") or base.get("voice", "af_heart")
    utterances = []
    for uid, line in lines.items():
        u = {"id": uid, "file": f"{uid}.wav", "text": line["text"]}
        role = cast.get(line["speaker"]) or {}
        voice = role.get("voice", narrator)
        if "speed" in role:              # a cast member's own pace (ElevenLabs takes 0.7-1.2)
            u["speed"] = role["speed"]
        # respelling helps the local voice; ElevenLabs reads names well and is given the real text
        spoken = line["directed"] if voice.startswith("eleven:") else respell(line["text"], say)
        if spoken != line["text"]:
            u["spoken"] = spoken
        if line["speaker"] != qc_script.NARRATOR:
            u.update(speaker=line["speaker"], mode=line["mode"], voice=voice)
        utterances.append(u)
    return {"voice": narrator, "speed": base.get("speed", 1.0), "utterances": utterances}


def respell(text, say):
    """The text as the voice should read it: whole words swapped by script/pronounce.json, one for one
    (punctuation kept), so captions keep the real spelling and word counts still line up."""
    if not say:
        return text
    word = re.compile(r"[A-Za-z][A-Za-z-]*")

    def swap(m):
        new = say.get(m.group(0))
        return new if new and len(new.split()) == 1 else m.group(0)
    return word.sub(swap, text)


def commands(stage, episode, args):
    """[argv] for a stage, or raises Blocked with the reason it cannot run yet."""
    ep = str(episode)
    tools = ROOT / "tools"
    if stage == "script":
        return [[PY, str(tools / "qc_script.py"), "--episode", ep]]
    if stage == "narration":
        models = Path(args.models)
        return [[PY, str(ROOT / "python" / "narrate.py"), "--input", str(episode / "script" / "narration-request.json"),
                 "--output", str(episode / "vo"), "--model", str(models / "kokoro-v1.0.onnx"),
                 "--voices", str(models / "voices-v1.0.bin")]]
    if stage == "shots":
        if (episode / "cut.json").is_file():
            # the cut list is authored, not planned; it is checked against the voice at `lengths`
            return [[PY, "-c", "print('cut.json is the shot table; nothing to plan')"]]
        return [[PY, str(tools / "plan_shots.py"), "--episode", ep]]
    if stage == "captions":
        # exact word times from the voice model first (skipped with a note when onnx is missing),
        # then captions and word_timing.json, which use them wherever they match the wav
        return [[PY, str(tools / "word_marks.py"), "--episode", ep, "--model", str(Path(args.models) / "kokoro-v1.0.onnx")],
                [PY, str(tools / "captions.py"), "--episode", ep]] + (
               # mouths for characters who speak on screen (an episode with only the narrator has none)
               [[PY, str(tools / "lip_sync.py"), "--episode", ep]] if has_characters(episode) else [])
    if stage == "lengths":
        return [[PY, str(tools / "assemble_episode.py"), "--episode", ep, "--shot-lengths-only"]]
    if stage == "plan":
        if (episode / "storyboard.json").is_file() and not args.replan:
            return [[PY, str(tools / "plan_storyboard.py"), "--episode", ep, "--check"]]
        if getattr(args, "ask_api", False):
            return [[PY, str(tools / "plan_storyboard.py"), "--episode", ep, "--ask-api"]]
        if args.ask_cmd:
            return [[PY, str(tools / "plan_storyboard.py"), "--episode", ep, "--ask-cmd", args.ask_cmd]]
        return [[PY, str(tools / "plan_storyboard.py"), "--episode", ep, "--brief"], "BLOCK:"
                "no storyboard.json and no --ask-cmd/--ask-api: the brief is written to storyboard-brief.md; "
                "give a planner command or write storyboard.json from it, then re-run"]
    if stage in ("ingest", "render"):
        return [[PY, str(tools / "rollout_render.py"), "--episode", ep, stage]]
    if stage == "assemble":
        return [[PY, str(tools / "assemble_episode.py"), "--episode", ep]]
    if stage == "qc":
        return [[PY, str(tools / "qc_episode.py"), "--episode", ep, "--master", str(episode / f"{episode.name}.mp4"),
                 "--json", str(episode / "qc" / "qc-report.json")]]
    raise KeyError(stage)


def load_state(episode):
    path = episode / "qc" / "make-episode.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def save_state(episode, state):
    (episode / "qc").mkdir(exist_ok=True)
    path = episode / "qc" / "make-episode.json"
    partial = path.with_name(path.name + ".tmp")     # a crash mid-write must not lose every finished stage
    partial.write_text(json.dumps(state, indent=1), encoding="utf-8")
    os.replace(partial, path)


def status(stage, episode, state, force):
    """'done' | 'run' (with a reason)."""
    try:
        now = digest(inputs_of(stage, episode))
    except OSError as exc:
        return "run", f"inputs unreadable ({exc})"
    record = state.get(stage)
    if force:
        return "run", "forced"
    if not record:
        return "run", "never run"
    if record["inputs"] != now:
        return "run", "inputs changed since it last ran"
    if not outputs_exist(stage, episode):
        return "run", "outputs missing"
    return "done", f"finished {record['finished']}"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--episode", type=Path, required=True)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--from", dest="first", choices=STAGES)
    ap.add_argument("--only", help="comma-separated stages")
    ap.add_argument("--force", action="store_true", help="run the selected stages even if they are done")
    ap.add_argument("--ask-cmd", help="planner command (see plan_storyboard.py)")
    ap.add_argument("--ask-api", action="store_true", help="plan the storyboard with Claude through the Anthropic API")
    ap.add_argument("--replan", action="store_true", help="plan again even though storyboard.json exists")
    ap.add_argument("--models", default=str(ROOT / "models" / "kokoro"))
    args = ap.parse_args(argv)
    episode = args.episode if args.episode.is_absolute() else ROOT / args.episode
    if not (episode / "script" / "narration.md").is_file():
        raise SystemExit(f"{episode}: no script/narration.md; write the script first")

    selected = STAGES
    if args.only:
        selected = [s for s in args.only.split(",") if s]
        unknown = [s for s in selected if s not in STAGES]
        if unknown:
            raise SystemExit(f"unknown stage(s) {unknown}; expected {STAGES}")
    elif args.first:
        selected = STAGES[STAGES.index(args.first):]

    state = load_state(episode)
    env = dict(os.environ)
    forced_downstream = False
    for stage in selected:
        state_now, why = status(stage, episode, state, args.force)
        if state_now == "done" and forced_downstream:
            state_now, why = "run", "an earlier stage re-runs"
        if state_now == "done":
            print(f"[{stage:9}] done     {why}")
            note = code_note(stage, state.get(stage))
            if note:
                print(f"            note: {note}")
            continue
        forced_downstream = True      # a stage that runs invalidates what depends on its outputs
        if stage == "narration":
            if not args.dry_run:
                (episode / "script" / "narration-request.json").write_text(
                    json.dumps(narration_request(episode), indent=1), encoding="utf-8")
        cmds = commands(stage, episode, args)
        blocked = next((c[6:] for c in cmds if isinstance(c, str) and c.startswith("BLOCK:")), None)
        argvs = [c for c in cmds if isinstance(c, list)]
        label = "would run" if args.dry_run else "running  "
        print(f"[{stage:9}] {label} ({why})")
        for a in argvs:
            shown = [Path(x).name if x == PY else (os.path.relpath(x, ROOT) if x.startswith(str(ROOT)) else x) for x in a]
            print("            " + " ".join(f'"{x}"' if " " in x else x for x in shown))
        if blocked:
            print(f"            BLOCKED: {blocked}" if args.dry_run else "")
        if args.dry_run:
            continue
        for a in argvs:
            code = subprocess.run(a, cwd=ROOT, env=env).returncode
            if code != 0:
                print(f"\nstage '{stage}' failed (exit {code}); fix it and re-run, finished stages are skipped",
                      file=sys.stderr)
                return code
        if blocked:
            print(f"\nstopped at '{stage}': {blocked}", file=sys.stderr)
            return 2
        state[stage] = {"inputs": digest(inputs_of(stage, episode)), "code": code_digest(stage),
                        "finished": datetime.now().isoformat(timespec="seconds")}
        save_state(episode, state)
    print("\nall selected stages are finished" if not args.dry_run else "\n(dry run: nothing was changed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
